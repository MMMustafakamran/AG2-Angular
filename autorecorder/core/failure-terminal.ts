/**
 * The terminal at the end of a failed take: a real shell, filmed live.
 *
 * It used to be a synthetic cast: text gathered from the server logs and the
 * browser console, formatted by the recorder and replayed in the terminal
 * window. That looked like a terminal but every line was the recorder's
 * choice, so it proved nothing a viewer could not suspect was written in
 * advance (owner, 2026-11-08: "i want it to be real terminal").
 *
 * Now the recorder spawns a real shell with node-pty in the repo root, types
 * ordinary commands into it at a human rhythm (`ls logs/`, `tail -n 25
 * <log>`, `grep -n ... <log>`), and streams exactly what that shell prints to
 * the terminal window as it prints it. Nothing on screen is generated by the
 * recorder: the prompt, the echo of every typed character and every output
 * byte come from the PTY. The same bytes are saved as a cast next to the
 * error log (`videos/logs/<page-id>.error-terminal.cast`).
 *
 * The browser console is not terminal output, so it is not printed here; it
 * stays in `videos/logs/<page-id>.error.log` (see failure-evidence.ts).
 *
 * Shell per platform: bash everywhere it exists (Git Bash on Windows, never
 * the WSL `System32\bash.exe`), PowerShell as the Windows fallback.
 * `QA_FAILURE_SHELL` overrides the path.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { type Cast } from './cli/cast';
import { PtySession, sleep } from './cli/session';
import { type LogSource, findAnchor } from './failure-evidence';
import { between, keystrokeDelay } from './overlays/human';

export type ShellKind = 'bash' | 'powershell';

export interface ShellSpec {
  kind: ShellKind;
  file: string;
  args: string[];
  env: Record<string, string>;
  /** Matches the screen text when the shell is waiting for a command. */
  prompt: RegExp;
}

/** Git for Windows install root (the folder holding bin\bash.exe), or null. */
function gitForWindowsRoot(): string | null {
  const roots = [
    process.env.ProgramW6432 && join(process.env.ProgramW6432, 'Git'),
    process.env.ProgramFiles && join(process.env.ProgramFiles, 'Git'),
    process.env['ProgramFiles(x86)'] && join(process.env['ProgramFiles(x86)']!, 'Git'),
    process.env.LOCALAPPDATA && join(process.env.LOCALAPPDATA, 'Programs', 'Git'),
  ].filter(Boolean) as string[];
  // Wherever git.exe is on PATH: <root>\cmd\git.exe or <root>\mingw64\bin\git.exe.
  for (const dir of (process.env.PATH ?? '').split(';')) {
    if (!dir || !existsSync(join(dir, 'git.exe'))) continue;
    const d = dir.replace(/[\\/]+$/, '');
    if (/[\\/]cmd$/i.test(d)) roots.push(dirname(d));
    if (/[\\/]mingw64[\\/]bin$/i.test(d)) roots.push(dirname(dirname(d)));
  }
  for (const r of roots) if (existsSync(join(r, 'bin', 'bash.exe'))) return r;
  return null;
}

/** A prompt that shows only the folder name: no user, no host, no full path. */
const BASH_PS1 = '\\[\\e[32m\\]\\W\\[\\e[0m\\] $ ';

export function pickShell(): ShellSpec | null {
  const bashEnv = (extraPath?: string): Record<string, string> => ({
    PS1: BASH_PS1,
    HISTFILE: '/dev/null',
    TERM: 'xterm-256color',
    CHERE_INVOKING: '1', // Git Bash: stay in the cwd we start it in
    ...(extraPath ? { PATH: `${extraPath};${process.env.PATH ?? ''}` } : {}),
  });
  const bashArgs = ['--noprofile', '--norc', '-i'];
  const bashPrompt = /\$\s*$/;

  const override = process.env.QA_FAILURE_SHELL;
  if (override && existsSync(override)) {
    const kind: ShellKind = /powershell|pwsh/i.test(override) ? 'powershell' : 'bash';
    return kind === 'bash'
      ? { kind, file: override, args: bashArgs, env: bashEnv(), prompt: bashPrompt }
      : { kind, file: override, args: ['-NoLogo', '-NoProfile'], env: {}, prompt: /PS [^\n]*>\s*$/ };
  }

  if (process.platform === 'win32') {
    const git = gitForWindowsRoot();
    if (git) {
      const usrBin = join(git, 'usr', 'bin');
      return {
        kind: 'bash',
        file: join(git, 'bin', 'bash.exe'),
        args: bashArgs,
        env: bashEnv(`${usrBin};${join(git, 'mingw64', 'bin')}`),
        prompt: bashPrompt,
      };
    }
    const ps = join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
    if (existsSync(ps)) {
      return { kind: 'powershell', file: ps, args: ['-NoLogo', '-NoProfile'], env: {}, prompt: /PS [^\n]*>\s*$/ };
    }
    return null;
  }

  for (const b of ['/bin/bash', '/usr/bin/bash', '/usr/local/bin/bash', '/opt/homebrew/bin/bash']) {
    if (existsSync(b)) return { kind: 'bash', file: b, args: bashArgs, env: bashEnv(), prompt: bashPrompt };
  }
  try {
    const found = execFileSync('sh', ['-c', 'command -v bash'], { encoding: 'utf8' }).trim();
    if (found) return { kind: 'bash', file: found, args: bashArgs, env: bashEnv(), prompt: bashPrompt };
  } catch {}
  return null;
}

const CRASH = /Traceback \(most recent call last\)|ModuleNotFoundError|ImportError|Cannot find module|EADDRINUSE|Error loading ASGI app/;

/** True when a log's last lines are a startup crash (the server behind it is dead). */
function endsInCrash(src: LogSource): boolean {
  try {
    const tail = readFileSync(src.path, 'utf8')
      .replace(/\x1b\[[0-9;]*[A-Za-z]/g, '')
      .split(/\r?\n/)
      .filter((l) => l.trim())
      .slice(-20);
    return tail.some((l) => CRASH.test(l));
  } catch {
    return false;
  }
}

/** The lines this page added to a log (since its offset), or [] if unreadable. */
function newLines(src: LogSource): string[] {
  try {
    if (statSync(src.path).size <= src.fromByte) return [];
    const buf = readFileSync(src.path);
    return buf
      .subarray(Math.min(src.fromByte, buf.length))
      .toString('utf8')
      .replace(/\x1b\[[0-9;]*[A-Za-z]/g, '')
      .split(/\r?\n/)
      .filter((l) => l.trim());
  } catch {
    return [];
  }
}

// `rendered nothing`: CopilotKit's dev warning when a tool call (e.g. render_ui) has no renderer;
// Next forwards it to the frontend log as `[browser] ...`, and it is the cause on generative-UI pages.
export const GREP_PATTERN = 'error|exception|failed|404|rendered nothing';

/**
 * Which logs to look at, in the order to look at them: logs this page wrote to
 * first, the one holding an error-like line last (its output is what stays on
 * screen). Falls back to every log when none grew. At most `max`.
 */
export function pickLogs(logs: LogSource[], max = 3): { logs: LogSource[]; grepLog: LogSource | null } {
  const scored = logs.map((src) => {
    const lines = newLines(src);
    return { src, grew: lines.length > 0, hasError: findAnchor(lines) >= 0, dead: false };
  });
  // A server that crashed at startup never writes during the take, yet its log holds the cause
  // (e.g. ModuleNotFoundError behind "fetch failed"). A log that ends in a crash and stayed silent
  // counts as grown, with an error.
  for (const s of scored) if (!s.grew && endsInCrash(s.src)) Object.assign(s, { grew: true, hasError: true, dead: true });
  const grown = scored.filter((s) => s.grew);
  const pool = grown.length ? grown : scored;
  const ordered = [...pool.filter((s) => !s.hasError), ...pool.filter((s) => s.hasError)].slice(-max);
  const last = ordered[ordered.length - 1];
  return { logs: ordered.map((s) => s.src), grepLog: last && last.hasError ? last.src : null };
}

function rel(rootDir: string, path: string): string {
  const r = relative(rootDir, path);
  return r.startsWith('..') ? path : r;
}

/** The commands typed into the shell, as a person would type them. */
export function failureCommands(kind: ShellKind, rootDir: string, logs: LogSource[]): string[] {
  const { logs: chosen, grepLog } = pickLogs(logs);
  const dirs = [...new Set(chosen.map((l) => rel(rootDir, dirname(l.path))))];
  const cmds: string[] = [];
  if (kind === 'bash') {
    const p = (s: string) => s.split(sep).join('/');
    const q = (s: string) => (/^[\w./-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`);
    for (const d of dirs.length ? dirs : ['logs']) cmds.push(`ls ${q(p(d))}/`);
    for (const l of chosen) cmds.push(`tail -n 25 ${q(p(rel(rootDir, l.path)))}`);
    if (grepLog) {
      cmds.push(`grep -n -i -E --color=always "${GREP_PATTERN}" ${q(p(rel(rootDir, grepLog.path)))} | tail -n 8`);
    }
  } else {
    const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
    for (const d of dirs.length ? dirs : ['logs']) cmds.push(`Get-ChildItem ${q(d)} -Name`);
    for (const l of chosen) cmds.push(`Get-Content ${q(rel(rootDir, l.path))} -Tail 25`);
    if (grepLog) {
      cmds.push(`Select-String -Pattern '${GREP_PATTERN}' ${q(rel(rootDir, grepLog.path))} | Select-Object -Last 8`);
    }
  }
  return cmds;
}

export interface FailureTerminalOptions {
  rootDir: string;
  logs: LogSource[];
  title: string;
  cols?: number;
  rows?: number;
  /** Called with every chunk the PTY prints, in order, as it prints it. */
  onData: (data: string) => void;
  /** Stop early (e.g. the overall time bound ran out). */
  signal?: { aborted: boolean };
}

/**
 * Runs the shell, types the commands, waits for each to finish. Returns the
 * cast of everything the PTY printed (real timing), or throws if no shell can
 * be started.
 */
export async function runFailureTerminal(opts: FailureTerminalOptions): Promise<{ cast: Cast; commands: string[]; shell: string }> {
  const shell = pickShell();
  if (!shell) throw new Error('no shell found for the failure terminal (bash / powershell)');
  const commands = failureCommands(shell.kind, opts.rootDir, opts.logs);

  const session = new PtySession({
    command: shell.file,
    args: shell.args,
    cwd: opts.rootDir,
    env: shell.env,
    cols: opts.cols ?? 120,
    rows: opts.rows ?? 32,
    echo: false,
    title: opts.title,
    onData: opts.onData,
  });
  try {
    const ready = await session.waitFor(shell.prompt, 15_000);
    if (!ready.matched) throw new Error(`shell prompt did not appear in 15s (${shell.file})`);
    await sleep(between(700, 1100));

    for (const cmd of commands) {
      if (opts.signal?.aborted) break;
      for (const ch of cmd) {
        session.send(ch);
        await sleep(keystrokeDelay(ch, { charDelayMs: 55 }));
      }
      await sleep(between(250, 450));
      session.send('\r');
      const done = await session.waitFor(shell.prompt, 15_000);
      if (!done.matched) break;
      // Time to read what it printed before the next command scrolls it.
      await sleep(between(2200, 3000));
    }
    return { cast: session.cast.build(), commands, shell: shell.file };
  } finally {
    session.kill();
  }
}
